    CrLev2Cp10s(0x8009),
    UseNanoSvH(0x800C),
    CrUnits(0x8013),
    DsLev1Ur(0x8014),
    DsLev2Ur(0x8015),
    Cps(0x8020),
    DrUrH(0x8021),
    DsUr(0x8022),
    TempDegC(0x8024),
    VBiasMv(0xC000),
    SysStatus(0xFFFF000B.toInt()),
    SysMcuTemp(0xFFFF000D.toInt()),
