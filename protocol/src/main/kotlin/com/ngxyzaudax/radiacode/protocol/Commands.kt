package com.ngxyzaudax.radiacode.protocol

enum class Command(val code: Int) {
    GetStatus(0x0005),
    SetExchange(0x0007),
    GetVersion(0x000A),
    GetSerial(0x000B),
    RdVirtSfr(0x0824),
    WrVirtSfr(0x0825),
    RdVirtString(0x0826),
    WrVirtString(0x0827),
    RdVirtSfrBatch(0x082A),
    WrVirtSfrBatch(0x082B),
    SetTime(0x0A04),
}

enum class VirtString(val id: Int) {
    Configuration(2),
    SerialNumber(8),
    DataBuf(0x100),
    SfrFile(0x101),
    Spectrum(0x200),
    EnergyCalib(0x202),
    SpecAccum(0x205),
}

